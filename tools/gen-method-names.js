#!/usr/bin/env node
// gen-method-names.js — generate the host-independent method-name list for listMethods
//
// Why this exists (2026-10-27, v1.11.0-fix2):
//   listMethods used to enumerate command classes via Assembly.GetTypes(). On a plain-AutoCAD
//   host a handful of types reference Civil 3D API types, so GetTypes() throws
//   ReflectionTypeLoadException; the swallowed exception left the list at the 23 hardcoded
//   AdditionalRegisteredNames — the AI then "could not see" createCircle/createPolyline at all.
//   The dispatcher switch is the real registry, so we bake it into source at build time.
//
// Usage:
//   node tools/gen-method-names.js           # write plugin/AcBridge-v24/src/MethodNames.g.cs
//   node tools/gen-method-names.js --check    # exit 1 if the checked-in file is stale

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DISP = path.join(ROOT, 'plugin', 'AcBridge-v24', 'src', 'CommandDispatcher.cs');
const OUT = path.join(ROOT, 'plugin', 'AcBridge-v24', 'src', 'MethodNames.g.cs');

const src = fs.readFileSync(DISP, 'utf8');
const block = src.match(/return method switch\s*\{([\s\S]*?)\n\s*\};/);
if (!block) {
  console.error('FATAL: dispatcher switch block not found');
  process.exit(1);
}

const names = [];
const seen = new Set();
for (const m of block[1].matchAll(/"([A-Za-z0-9_]+)"\s*=>/g)) {
  if (seen.has(m[1])) continue;
  seen.add(m[1]);
  names.push(m[1]);
}
if (names.includes('dispatch')) {
  const i = names.indexOf('dispatch');
  names.splice(i, 1);
}
names.sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));
if (names.length < 300) {
  console.error('FATAL: parsed only ' + names.length + ' names — parser is probably broken');
  process.exit(1);
}

const lines = [];
lines.push('// <auto-generated>');
lines.push('// Generated by tools/gen-method-names.js from the CommandDispatcher switch — DO NOT EDIT.');
lines.push('// Regenerate after adding/removing a dispatcher arm; `node tools/gen-method-names.js --check`');
lines.push('// fails when this file drifts from the switch.');
lines.push('// </auto-generated>');
lines.push('');
lines.push('namespace Civil3DMcpPlugin;');
lines.push('');
lines.push('internal static class MethodNames');
lines.push('{');
lines.push('  public const int Count = ' + names.length + ';');
lines.push('');
lines.push('  public static readonly string[] All =');
lines.push('  {');
for (let i = 0; i < names.length; i += 6) {
  const chunk = names.slice(i, i + 6).map(n => '"' + n + '"').join(', ');
  lines.push('    ' + chunk + ',');
}
lines.push('  };');
lines.push('}');
lines.push('');
const content = lines.join('\n');

const check = process.argv.includes('--check');
const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
if (check) {
  if (existing === content) {
    console.log('[OK] MethodNames.g.cs matches the dispatcher switch (' + names.length + ' methods)');
    process.exit(0);
  }
  console.error('[FAIL] MethodNames.g.cs is stale — run: node tools/gen-method-names.js');
  if (existing) {
    const oldNames = new Set([...existing.matchAll(/"([A-Za-z0-9_]+)"/g)].map(m => m[1]));
    const added = names.filter(n => !oldNames.has(n));
    const removed = [...oldNames].filter(n => !seen.has(n));
    if (added.length) console.error('  + ' + added.join(', '));
    if (removed.length) console.error('  - ' + removed.join(', '));
  }
  process.exit(1);
}

fs.writeFileSync(OUT, content, 'utf8');
console.log('[OK] wrote ' + path.relative(ROOT, OUT) + ' (' + names.length + ' methods)');
